local Addon = require("helpers.load_addon")

-- A Rogue with a weapon in each hand
local function rogue(opts)
    opts = opts or {}
    local h = Addon.load({ class = "ROGUE", config = opts.config, translate = opts.translate })
    h:equipOffHand(2092)
    return h
end

describe("Rogue poisons", function()
    it("applies the poison to the main hand, then the off hand", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        assert.same({ "Instant Poison on 16", "Instant Poison on 17" }, h:buffUp())
    end)

    it("uses the poison by item ID, so it works in any client language", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        assert.equal("/use item:6947\n/use 16", h.button:GetAttribute("macrotext1"))
        assert.equal("Interface\\Icons\\Instant Poison", h.button:GetNormalTexture():GetTexture())
    end)

    it("uses the highest rank in the bags", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        h:bag("Instant Poison III", 5)
        assert.equal("Instant Poison III on 16", h:shown())
    end)

    it("uses the poison chosen for each hand", function()
        local h = rogue({ config = { ROGUE_POISON_MAINHAND = "Instant Poison", ROGUE_POISON_OFFHAND = "Deadly Poison" } })
        h:bag("Instant Poison", 5)
        h:bag("Deadly Poison II", 5)
        assert.same({ "Instant Poison on 16", "Deadly Poison II on 17" }, h:buffUp())
    end)

    it("falls back to another poison when the chosen one is out", function()
        local h = rogue({ config = { ROGUE_POISON_MAINHAND = "Deadly Poison" } })
        h:bag("Crippling Poison", 5)
        assert.equal("Crippling Poison on 16", h:shown())
        h:bag("Deadly Poison", 5)
        assert.equal("Deadly Poison on 16", h:shown())
    end)

    it("is skipped with no poison in the bags, and back once some are bought", function()
        local h = rogue()
        assert.is_nil(h:shown())
        h:bag("Instant Poison", 5)
        assert.equal("Instant Poison on 16", h:shown())
        h:bag("Instant Poison", 0)
        assert.is_nil(h:shown())
    end)

    it("skips the off hand without an off-hand weapon", function()
        local h = rogue()
        h:equipOffHand(nil)
        h:bag("Instant Poison", 5)
        assert.same({ "Instant Poison on 16" }, h:buffUp())
    end)

    it("skips the main hand without a main-hand weapon", function()
        local h = rogue()
        h.state.mainHand = nil
        h:bag("Instant Poison", 5)
        assert.same({ "Instant Poison on 17" }, h:buffUp())
    end)

    it("checks each hand on its own", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        h:enchantWeapon(2, nil, { slot = 1, charges = 60 })
        assert.same({ "Instant Poison on 16" }, h:buffUp())
        h:clearWeaponEnchant(1)
        assert.equal("Instant Poison on 17", h:shown())
    end)

    it("counts an oil or stone on that hand", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        h:enchantWeapon(2)
        assert.equal("Instant Poison on 17", h:shown())
    end)

    it("shows again with under 10 charges", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        h:enchantWeapon(2, nil, { charges = 9 })
        assert.equal("Instant Poison on 16", h:shown())
        h:enchantWeapon(2, nil, { charges = 10 })
        assert.equal("Instant Poison on 17", h:shown())
    end)

    it("shows again with under 5 minutes left", function()
        local h = rogue()
        h:bag("Instant Poison", 5)
        h:enchantWeapon(2, 299000, { charges = 60 })
        assert.equal("Instant Poison on 16", h:shown())
    end)

    it("lists the poisons by the client's item names", function()
        local h = rogue({ translate = function(name) return "DE " .. name end })
        h:bag("Instant Poison II", 5)
        assert.same({ "DE Instant Poison II", "DE Instant Poison II" }, h:suggestions())
    end)

    describe("settings", function()
        it("picks one poison per hand", function()
            local h = rogue()
            h:slash("")
            assert.equal(5, #h:dropdown("Rogue off hand poison"))
            assert.equal("Instant Poison", h:selected("Rogue off hand poison"))
            h:choose("Rogue off hand poison", "Deadly Poison")
            assert.equal("Deadly Poison", h.ns.config.ROGUE_POISON_OFFHAND)
            assert.equal("Deadly Poison", h:selected("Rogue off hand poison"))
            assert.equal("Instant Poison", h:selected("Rogue main hand poison"))
        end)

        it("takes effect immediately", function()
            local h = rogue()
            h:bag("Instant Poison", 5)
            h:bag("Crippling Poison", 5)
            h:slash("")
            h:choose("Rogue main hand poison", "Crippling Poison")
            assert.equal("Crippling Poison on 16", h:shown())
        end)

        it("shows the client's poison names", function()
            local h = rogue({ translate = function(name) return "DE " .. name end })
            h:slash("")
            assert.equal("DE Instant Poison", h:selected("Rogue main hand poison"))
        end)
    end)
end)
