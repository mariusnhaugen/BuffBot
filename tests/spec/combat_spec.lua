local Addon = require("helpers.load_addon")

describe("combat", function()
    local h

    before_each(function()
        h = Addon.load({ class = "MAGE", known = { "Arcane Intellect", "Dampen Magic" } })
    end)

    it("hides the button on entering combat", function()
        assert.equal("Arcane Intellect", h:shown())
        h:enterCombat()
        assert.is_false(h.button:IsShown())
    end)

    it("does not touch the secure button in combat", function()
        h:enterCombat()
        h.ns.UpdateMacro("Dampen Magic", "player")
        assert.equal("/cast [target=player]Arcane Intellect", h.button:GetAttribute("macrotext1"))
        assert.is_false(h.button:IsShown())
    end)

    it("stays hidden when auras change in combat", function()
        h:enterCombat()
        h:give("Arcane Intellect")
        h:remove("Arcane Intellect")
        assert.is_false(h.button:IsShown())
    end)

    it("re-checks on leaving combat", function()
        h:enterCombat()
        h.state:giveAura("Arcane Intellect")
        h:leaveCombat()
        assert.equal("Dampen Magic", h:shown())
    end)

    it("stays hidden after combat when fully buffed", function()
        h:enterCombat()
        h.state:giveAura("Arcane Intellect")
        h.state:giveAura("Dampen Magic")
        h:leaveCombat()
        assert.is_nil(h:shown())
    end)

    -- Auras can't be read once a boss is pulled, and the player can still be
    -- out of combat then: everything would look missing
    describe("in a boss fight, before the player's combat", function()
        local function buffed()
            local b = Addon.load({ class = "MAGE", known = { "Arcane Intellect" } })
            b:joinParty({ { class = "PRIEST" } })
            b:give("Arcane Intellect")
            b.state:giveAura("Arcane Intellect", { unit = "party1" })
            b:fire("UNIT_AURA", "party1", {})
            b.state:advance(0.5)
            assert.is_nil(b:shown())
            return b
        end

        it("stays hidden when a member's auras change", function()
            local b = buffed()
            b:startEncounter()
            b:fire("UNIT_AURA", "party1", {})
            b.state:advance(0.5)
            assert.is_nil(b:shown())
        end)

        it("stays hidden when the player's auras change", function()
            local b = buffed()
            b:startEncounter()
            b:fire("UNIT_AURA", "player", {})
            assert.is_nil(b:shown())
        end)

        it("hides a button already up when the fight starts", function()
            assert.equal("Arcane Intellect", h:shown())
            h:startEncounter()
            assert.is_nil(h:shown())
        end)

        it("stays hidden if the player's combat ends before the fight does", function()
            local b = buffed()
            b:startEncounter()
            b:enterCombat()
            b:leaveCombat()
            assert.is_nil(b:shown())
        end)

        it("re-checks when the fight ends", function()
            h:startEncounter()
            h:endEncounter()
            assert.equal("Arcane Intellect", h:shown())
        end)

        it("leaves the button alone if the fight ends with the player in combat", function()
            h:startEncounter()
            h:enterCombat()
            h:endEncounter()
            assert.is_nil(h:shown())
            h:leaveCombat()
            assert.equal("Arcane Intellect", h:shown())
        end)
    end)
end)
